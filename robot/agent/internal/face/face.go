// Package face renders the Anki Vector face LCD: 184×96 RGB565.
package face

import (
	"os"
	"strings"
)

// Anki vector-python-sdk screen.py: 184×96 RGB565, 35328 bytes.
// The replacement panel is ST0103A2W-WSNLW-F, 1.03 in, 184×96.
const (
	Width  = 184
	Height = 96
	Bytes  = Width * Height * 2
)

func RGB565(r, g, b uint8) uint16 {
	return (uint16(r>>3) << 11) | (uint16(g>>2) << 5) | uint16(b>>3)
}

var (
	Green = RGB565(0, 230, 170) // Anki default teal (hue 0.42)
	Red   = RGB565(220, 24, 24)
	Amber = RGB565(220, 180, 16)
	Black = RGB565(0, 0, 0)
	White = RGB565(255, 255, 255)
	Cyan  = RGB565(0, 230, 200)
)

func Frame(text string, fg uint16) []byte {
	buf := make([]byte, Bytes)
	blitText(buf, text, fg, 0)
	return buf
}

// ThinkingFrame is the DDL default pose with a squint, not a UI bar.
func ThinkingFrame(phase float64) []byte {
	return EyesThinking(phase)
}

func blitText(buf []byte, text string, fg uint16, yShift int) {
	text = strings.ToUpper(strings.TrimSpace(text))
	if text == "" {
		return
	}
	scale := 3
	if len(text) > 8 {
		scale = 2
	}
	tw := len(text) * 6 * scale
	th := 7 * scale
	x0 := (Width - tw) / 2
	y0 := (Height-th)/2 + yShift
	if x0 < 0 {
		x0 = 2
	}
	if y0 < 0 {
		y0 = 2
	}
	for i, ch := range text {
		drawGlyph(buf, x0+i*6*scale, y0, ch, fg, scale)
	}
}

func WriteDev(path string, frame []byte) error {
	if path == "" {
		return nil
	}
	return os.WriteFile(path, frame, 0644)
}

func Caption(s string) string {
	return strings.ToUpper(strings.TrimSpace(s))
}

func drawGlyph(buf []byte, x, y int, ch rune, fg uint16, scale int) {
	g, ok := font5x7[ch]
	if !ok {
		g = font5x7['?']
	}
	for row := 0; row < 7; row++ {
		bits := g[row]
		for col := 0; col < 5; col++ {
			if bits&(1<<(4-col)) == 0 {
				continue
			}
			for dy := 0; dy < scale; dy++ {
				for dx := 0; dx < scale; dx++ {
					px := x + col*scale + dx
					py := y + row*scale + dy
					if px < 0 || py < 0 || px >= Width || py >= Height {
						continue
					}
					put(buf, px, py, fg)
				}
			}
		}
	}
}

